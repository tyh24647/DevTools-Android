import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {runCommand} from '../FirefoxExtension/controller.js';
import {registration} from '../FirefoxExtension/user-scripts.js';
import fs from 'node:fs/promises';
const browser=await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:412,height:915}});
 await page.route('https://parity.test/**',r=>r.fulfill({contentType:'text/html',body:'<!doctype html><main><h1>Article</h1><p>'+ 'Readable article content. '.repeat(30)+'</p></main>'}));
 await page.goto('https://parity.test/');
 const frontendFiles={};for(const id of ['vue','vueLegacy','vueVConsole'])frontendFiles['tools/frontends/'+id+'.gz']=(await fs.readFile('FirefoxExtension/tools/frontends/'+id+'.gz')).toString('base64');
 const api={runtime:{getURL: path=>'data:application/octet-stream;base64,'+frontendFiles[path]},scripting:{executeScript:async({func,args=[],files})=>{if(files){for(const file of files)await page.addScriptTag({path:'FirefoxExtension/'+file});return [{frameId:0}];}return [{frameId:0,result:await page.evaluate(({fn,args})=>(0,eval)(`(${fn})`)(...args),{fn:func.toString(),args})}];}}};
 page.on('pageerror',e=>console.error(e.message));
 const profile={enabled:true,pro:true,console:{code:true,dom:true,fps:true,features:true,timing:true,resourceTiming:true,wrapText:false,entryColor:'#abcdef',codeFont:"'Courier New', Courier, monospace"},mediaConnected:true};
 assert.equal((await runCommand(api,1,'show',profile)).active,true);
 assert.deepEqual(await page.evaluate(()=>['code','dom','fps','features','timing','resource timing','css-editor'].filter(name=>!__DTAssets.eruda.get(name))),[]);
 await page.evaluate(()=>{__DTAssets.eruda.show('dom');__DTAssets.eruda.show();});
 assert.ok(await page.locator('#eruda').locator('.eruda-dom-tree .eruda-tree-item').count());
 await page.evaluate(()=>__DTAssets.eruda.get('dom').select(document.querySelector('h1')));
 assert.equal(await page.evaluate(()=>__DTAssets.eruda.get('dom')._selectedEl.tagName),'H1');
 await page.locator('#eruda').getByText('Inspect Selected Element',{exact:true}).click();
 assert.equal(await page.evaluate(()=>__DTAssets.eruda.get('elements')._$el.get(0).getBoundingClientRect().height>0),true);
 const root=page.locator('#eruda');assert.equal(await root.locator('.dt-resize-grip').count(),1);
 assert.equal(await page.evaluate(()=>devtoolsMedia.firefox),true);
 const user=registration({id:'test',name:'Test',kind:'userscript',source:'// ==UserScript==\n// @match https://parity.test/*\n// @grant GM_setValue\n// @grant GM_getValue\n// ==/UserScript==\nGM_setValue("x", 7);window.result=GM_getValue("x");'});
 await page.addScriptTag({content:user.js[0].code});assert.equal(await page.evaluate(()=>window.result),7);
 await page.addScriptTag({content:registration({id:'custom',name:'Custom',kind:'eruda',source:'return {name:"my-panel",init($el){$el.text("custom panel")}};'}).js[0].code});
 assert.equal(await page.evaluate(()=>!!__DTAssets.eruda.get('my-panel')),true);
 assert.equal(await page.evaluate(await fs.readFile('app/src/main/assets/tools/reader.js','utf8')),true);
 assert.equal(await page.locator('#__dt_reader').count(),1);
 assert.equal(await page.evaluate(await fs.readFile('app/src/main/assets/tools/reader.js','utf8')),false);
 await runCommand(api,1,'show',{...profile,console:{...profile.console,vue:true}});
 assert.equal(await page.evaluate(()=>!!__DTAssets.vue),true);
 assert.equal(await page.evaluate(()=>!!__DTAssets.eruda.get('vue')),true);
 await runCommand(api,1,'show',{...profile,console:{...profile.console,vue:true,vueAdapter:'legacy'}});
 assert.equal(await page.evaluate(()=>!!__DTAssets.vueLegacy),true);
 await page.evaluate(()=>__DTAssets.eruda.show('Vue'));
 const frame=page.locator('#eruda').locator('#vue-iframe');
 assert.equal(await frame.evaluate(el=>getComputedStyle(el).position),'relative');
 const panelBox=await page.locator('#eruda').locator('.eruda-dev-tools').boundingBox();
 const frameBox=await frame.boundingBox();assert.ok(frameBox.height<=panelBox.height);
 const consoleHeight=await page.locator('#eruda').locator('.eruda-dev-tools').evaluate(el=>el.getBoundingClientRect().height);
 const width=await page.evaluate(()=>document.querySelector('main').getBoundingClientRect().width);
 await page.evaluate(()=>document.documentElement.style.zoom='1.5');assert.ok(await page.evaluate(()=>getComputedStyle(document.documentElement).zoom)==='1.5');
 assert.ok(await page.evaluate(()=>document.querySelector('main').offsetWidth)<width);
 await page.waitForTimeout(50);
 const zoomedHeight=await page.locator('#eruda').locator('.eruda-dev-tools').evaluate(el=>el.getBoundingClientRect().height);
 assert.ok(Math.abs(zoomedHeight-consoleHeight)<2,`Console must keep its viewport height during page zoom: ${consoleHeight} -> ${zoomedHeight}`);
 console.log('PASS: Firefox optional panels, CSS, custom plugin, granted userscript storage, media adapter, article reader and layout zoom.');
} finally {await browser.close();}
